_cache: dict[str, tuple[int, str]] = {}


def _run(rid: str) -> tuple[int, str]:
    args = shlex.split(RUNS[rid])
    r = subprocess.run([LUA, str(HERE / "harness.lua"), "-q", "--flavor", "forever", *args, str(ADDON)],
                       cwd=ROOT, capture_output=True, text=True, timeout=900)
    return r.returncode, r.stdout + r.stderr


@pytest.fixture(scope="module")
def forever_runs():
    """All runs at once, 4 in parallel (each is a separate lua5.1 process) — except under pytest-xdist, where this
    module fixture exists once per worker: each test then runs only its own replay (no run done 8 times)."""
    if not _cache and not os.environ.get("PYTEST_XDIST_WORKER"):
        with cf.ThreadPoolExecutor(4) as ex:
            for rid, res in zip(RUNS, ex.map(_run, RUNS)):
                _cache[rid] = res
    return _cache


def _verdict(rc: int, out: str, what: str, session: bool = False):
    ids, rest = forever_known.classify(out, session=session)
    assert not rest, ("%s: NEW failure(s) on the faithful Forever mock — a real-game bug or a scenario relying on "
                      "mock-only behaviour (see research/fidelity.md):\n  " % what) + "\n  ".join(p[:400] for p in rest[:25])
    if ids:
        pytest.xfail("FIDELITY: known real bugs %s (research/fidelity.md)" % ",".join(ids))
    if session:   # 4.0: every budget judged on forever too (the real client), as on modern
        assert re.search(r"RESULT ok session .* errors=0 swallowed=0 violations=0 fails=0", out), out[-3000:]
    else:
        assert rc == 0 and "RESULT ok" in out, out[-3000:]


def test_reference_in_sync_with_snapshot(tmp_path, monkeypatch):
    """forever_ref.lua is what forever_api_check.py generates from the committed snapshot (never hand-edited)."""
    snap = forever_api_check.load_snapshot()
    target = tmp_path / "forever_ref.lua"
    monkeypatch.setattr(forever_api_check, "LUA_REF", target)
    forever_api_check.write_lua_ref(snap)
    assert target.read_text(encoding="utf-8") == (HERE / "forever_ref.lua").read_text(encoding="utf-8"), \
        "tests/wow/forever_ref.lua is stale: run python tests/wow/forever_api_check.py"
    assert snap["source"]["build"].startswith("1.60") and len(snap["funcs"]) > 4000


@needs_lua
def test_mock_defines_no_api_the_client_lacks(tmp_path):
    rc = forever_api_check.main(["--addon", str(ADDON), "--out", str(tmp_path / "fidelity.md"), "--check"])
    assert rc == 0
    text = (tmp_path / "fidelity.md").read_text(encoding="utf-8")
    assert "| API | real (Forever 1.60.1)" in text and "mock defines it, the real client does not" not in text


