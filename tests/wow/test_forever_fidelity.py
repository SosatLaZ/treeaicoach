@needs_lua
@pytest.mark.parametrize("rid", list(RUNS))
def test_scenario_on_forever(forever_runs, rid):
    if rid not in forever_runs:
        forever_runs[rid] = _run(rid)
    rc, out = forever_runs[rid]
    _verdict(rc, out, rid)


