_TOK = re.compile(r"""
    (?P<ws>\s+)
  | (?P<lcomment>--\[(?P<eq>=*)\[.*?\](?P=eq)\])
  | (?P<comment>--[^\n]*)
  | (?P<str>"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')
  | (?P<num>0[xX][0-9a-fA-F]+|\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+)
  | (?P<name>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<op>[{}()\[\]=,;.:\-+*/])
""", re.S | re.X)


def _tokens(src: str):
    pos, n = 0, len(src)
    while pos < n:
        m = _TOK.match(src, pos)
        if not m:
            raise ValueError("bad token at %d: %r" % (pos, src[pos:pos + 20]))
        pos = m.end()
        kind = m.lastgroup
        if kind in ("ws", "lcomment", "comment"):
            continue
        if kind == "eq":
            continue
        yield kind, m.group(kind)


def _unquote(s: str) -> str:
    body = s[1:-1]
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), body)


class _Parser:
    def __init__(self, src):
        self.toks = list(_tokens(src))
        self.i = 0

    def peek(self, k=0):
        j = self.i + k
        return self.toks[j] if j < len(self.toks) else (None, None)

    def take(self):
        t = self.peek()
        self.i += 1
        return t

    def value(self):
        v = self.primary()
        while self.peek()[0] == "op" and self.peek()[1] in "+-*/" and self.peek()[1]:
            op = self.take()[1]
            rhs = self.primary()
            v = (v + rhs if op == "+" else v - rhs if op == "-" else v * rhs if op == "*" else v / rhs) \
                if isinstance(v, float) and isinstance(rhs, float) else "%s %s %s" % (v, op, rhs)
        return v

    def primary(self):
        kind, v = self.take()
        if kind == "op" and v == "{":
            return self.table()
        if kind == "str":
            return _unquote(v)
        if kind == "num":
            return float(int(v, 16)) if v.lower().startswith("0x") else float(v)
        if kind == "op" and v == "-":
            x = self.primary()
            return -x if isinstance(x, float) else "-%s" % x
        if kind == "op" and v == "(":
            x = self.value()
            self.take()
            return x
        if kind == "name":
            if v == "true":
                return True
            if v == "false":
                return False
            if v == "nil":
                return None
            parts = [v]
            while self.peek() == ("op", "."):
                self.take()
                parts.append(self.take()[1])
            return ".".join(parts)
        raise ValueError("unexpected %r %r" % (kind, v))

    def table(self):
        named, arr = {}, []
        while True:
            kind, v = self.peek()
            if kind == "op" and v == "}":
                self.take()
                break
            if kind == "name" and self.peek(1) == ("op", "="):
                self.take()
                self.take()
                named[v] = self.value()
            elif kind == "op" and v == "[":
                self.take()
                key = self.value()
                self.take()  # ]
                self.take()  # =
                named[key] = self.value()
            else:
                arr.append(self.value())
            if self.peek() in (("op", ","), ("op", ";")):
                self.take()
        if named and arr:
            for i, x in enumerate(arr):
                named[i + 1] = x
            return named
        return named if named else arr


def parse_doc_file(src: str):
    """The documentation table of one *Documentation.lua file (local X = { ... })."""
    m = re.search(r"^local\s+\w+\s*=\s*", src, re.M)
    if not m:
        return None
    p = _Parser(src[m.end():])
    if p.take() != ("op", "{"):
        return None
    return p.table()


FN_SKIP = {"Name", "Type", "Arguments", "Returns", "Documentation"}


def _params(lst):
    out = []
    for a in lst or []:
        if isinstance(a, dict):
            t = a.get("Type", "?")
            if a.get("InnerType"):
                t = "%s<%s>" % (t, a["InnerType"])
            out.append([a.get("Name", "?"), t, 1 if a.get("Nilable") else 0])
    return out


def _flags(d, skip):
    out = {}
    for k, v in d.items():
        if k in skip or not isinstance(k, str):
            continue
        if isinstance(v, (list, dict)):
            v = json.dumps(v, sort_keys=True)
        out[k] = v
    return out


def parse_docs(doc_dir: Path):
    funcs, methods, events, tables = {}, {}, {}, {}
    for f in sorted(doc_dir.glob("*.lua")):
        try:
            t = parse_doc_file(f.read_text(encoding="utf-8", errors="replace"))
        except ValueError as e:
            print("warn: %s: %s" % (f.name, e), file=sys.stderr)
            continue
        if not isinstance(t, dict):
            continue
        ns = t.get("Namespace")
        is_obj = t.get("Type") == "ScriptObject"
        for fn in t.get("Functions") or []:
            if not isinstance(fn, dict) or "Name" not in fn:
                continue
            rec = {"a": _params(fn.get("Arguments")), "r": _params(fn.get("Returns")), "f": _flags(fn, FN_SKIP)}
            if is_obj:
                methods["%s:%s" % (t.get("Name"), fn["Name"])] = rec
            else:
                funcs[(ns + "." if ns else "") + fn["Name"]] = rec
        for ev in t.get("Events") or []:
            if isinstance(ev, dict) and ev.get("LiteralName"):
                events[ev["LiteralName"]] = {"p": _params(ev.get("Payload")),
                                             "f": _flags(ev, FN_SKIP | {"LiteralName", "Payload"})}
        for tb in t.get("Tables") or []:
            if not isinstance(tb, dict) or "Name" not in tb:
                continue
            kind = tb.get("Type")
            rec = {"t": kind}
            if kind == "Enumeration":
                rec["v"] = {fl["Name"]: int(fl.get("EnumValue") or 0) for fl in tb.get("Fields") or []
                            if isinstance(fl, dict) and "Name" in fl and isinstance(fl.get("EnumValue"), float)}
            elif kind in ("Structure", "Constants"):
                rec["fields"] = _params(tb.get("Fields")) if kind == "Structure" else \
                    [[fl.get("Name"), fl.get("Type"), 0] for fl in tb.get("Values") or [] if isinstance(fl, dict)]
            tables[tb["Name"]] = rec
    return funcs, methods, events, tables


# ----------------------------------------------------------------------------------------------------------------
# 2. FrameXML that loads for camelot: TOC resolution + globals defined / C functions called / named frames
# ----------------------------------------------------------------------------------------------------------------
_ANN = re.compile(r"\[(AllowLoadGameType|ExcludeLoadGameType|AllowLoad|AllowLoadEnvironment|AllowLoadTextLocale)"
                  r"\s*([^\]]*)\]")


def _game_ok(text: str) -> bool:
    for kind, arg in _ANN.findall(text):
        games = {g.strip().lower() for g in arg.split(",") if g.strip()}
        if kind == "AllowLoadGameType" and not games & GAME_TOKENS:
            return False
        if kind == "ExcludeLoadGameType" and games & GAME_TOKENS:
            return False
        if kind == "AllowLoad" and games and games <= {"glue"}:
            return False
    return True


def resolve_framexml(addons_dir: Path):
    """Lua / XML files Blizzard loads (or can load on demand) in the camelot game, + deprecated-shim files."""
    lua_files, xml_files, shim_files, skipped_addons = [], [], [], []
    for d in sorted(p for p in addons_dir.iterdir() if p.is_dir()):
        if d.name == "Blizzard_APIDocumentationGenerated":
            continue
        tocs = sorted(d.glob("*.toc"))
        toc = next((t for t in tocs if t.stem == d.name), tocs[0] if tocs else None)
        if toc is None:
            continue
        lines = toc.read_text(encoding="utf-8", errors="replace").splitlines()
        header_ok = True
        for ln in lines:
            m = re.match(r"^##\s*(AllowLoadGameType|ExcludeLoadGameType|AllowLoad)\s*:\s*(.*)$", ln.strip())
            if not m:
                continue
            key, val = m.group(1), m.group(2)
            if _ANN.search(val) and not _game_ok(val):
                continue   # « ## AllowLoad: game [AllowLoadGameType classic] »: a header line for another game
            games = {g.strip().lower() for g in _ANN.sub("", val).split(",") if g.strip()}
            if key == "AllowLoadGameType" and not games & GAME_TOKENS:
                header_ok = False
            if key == "ExcludeLoadGameType" and games & GAME_TOKENS:
                header_ok = False
            if key == "AllowLoad" and games and games <= {"glue"}:
                header_ok = False
        if not header_ok:
            skipped_addons.append(d.name)
            continue
        shim = d.name.startswith("Blizzard_Deprecated")
        seen = set()

        def add(rel: str, depth=0):
            rel = rel.replace("\\", "/").replace("[Family]", FAMILY).replace("[Game]", "Camelot")
            if "[" in rel:  # [Bootstrap] & co: not the game
                return
            p = (d / rel)
            if p in seen or not p.is_file():
                return
            seen.add(p)
            if p.suffix.lower() == ".lua":
                (shim_files if shim else lua_files).append(p)
            elif p.suffix.lower() == ".xml" and depth < 10:
                xml_files.append(p)
                src = p.read_text(encoding="utf-8", errors="replace")
                for tag, f in re.findall(r"<(Script|Include)\s+file\s*=\s*\"([^\"]+)\"", src):
                    base = os.path.relpath(p.parent, d)
                    add(os.path.normpath(os.path.join(base, f.replace("\\", "/"))), depth + 1)

        for ln in lines:
            s = ln.strip()
            if not s or s.startswith("#"):
                continue
            if not _game_ok(s):
                continue
            add(_ANN.sub("", s).strip())
    return lua_files, xml_files, shim_files, skipped_addons


_LUA_WORDS = set("and break do else elseif end false for function if in local nil not or repeat return then true "
                 "until while self".split())
_LUA_STRIP = re.compile(r"--\[(=*)\[.*?\]\1\]|--[^\n]*", re.S)


def _strip_comments(s: str) -> str:
    return _LUA_STRIP.sub(lambda m: "\n" * m.group(0).count("\n"), s)


def scan_framexml(lua_files, xml_files, shim_files):
    defined, called, frames, shim_defined, ev_strings = set(), collections.Counter(), set(), set(), set()
    fallback = collections.Counter()
    for f in lua_files:
        t = _strip_comments(f.read_text(encoding="utf-8", errors="replace"))
        local = set(re.findall(r"\blocal\s+function\s+([A-Za-z_]\w*)", t))
        for m in re.finditer(r"\blocal\s+([A-Za-z_][\w\s,]*?)\s*(?:=|$)", t, re.M):
            local.update(x.strip() for x in m.group(1).split(","))
        for m in re.finditer(r"^\s*function\s+([A-Za-z_][\w.]*)\s*\(", t, re.M):
            defined.add(m.group(1))
        for m in re.finditer(r"^([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?)\s*=(?!=)", t, re.M):
            defined.add(m.group(1))
        file_calls = set()
        for m in re.finditer(r"(?<![.:\w])([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?)\s*\(", t):
            head = m.group(1).split(".")[0]
            if head not in local and head not in _LUA_WORDS:
                file_calls.add(m.group(1))
        for n in file_calls:
            # a global called next to its C_X.Name twin is a feature-test fallback (« if C_X then … else Name() »):
            # weak evidence, counted apart
            if "." not in n and re.search(r"\bC_\w+\.%s\b" % re.escape(n), t):
                fallback[n] += 1
            else:
                called[n] += 1
        ev_strings.update(re.findall(r"Register(?:Unit)?Event\w*\(\s*(?:[\w.]+\s*,\s*)?\"([A-Z][A-Z0-9_]{4,})\"", t))
    for f in shim_files:
        t = _strip_comments(f.read_text(encoding="utf-8", errors="replace"))
        for m in re.finditer(r"^\s*function\s+([A-Za-z_][\w.]*)\s*\(", t, re.M):
            shim_defined.add(m.group(1))
        for m in re.finditer(r"^\s*([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?)\s*=(?!=)", t, re.M):
            shim_defined.add(m.group(1))
    for f in xml_files:
        t = f.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r"<(?:Frame|Button|CheckButton|StatusBar|GameTooltip|ScrollFrame|EditBox|Slider|"
                             r"MessageFrame|ScrollingMessageFrame|Minimap|Cooldown|Model|PlayerModel|SimpleHTML|"
                             r"ColorSelect|MovieFrame|Texture|FontString|Font)\b[^>]*\bname=\"([A-Za-z_]\w*)\"", t):
            frames.add(m.group(1))
        ev_strings.update(re.findall(r"<On\w+|event=\"([A-Z][A-Z0-9_]{4,})\"", t))
    ev_strings.discard("")
    return defined, called, frames, shim_defined, ev_strings, fallback


