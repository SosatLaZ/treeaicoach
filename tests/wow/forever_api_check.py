def build_snapshot(ui_root: Path) -> dict:
    addons = ui_root / "Interface" / "AddOns"
    if not addons.is_dir():
        addons = ui_root
    funcs, methods, events, tables = parse_docs(addons / "Blizzard_APIDocumentationGenerated")
    lua_files, xml_files, shim_files, skipped = resolve_framexml(addons)
    defined, called, frames, shim_defined, ev_strings, fallback = scan_framexml(lua_files, xml_files, shim_files)
    # an undocumented global whose name also lives in a documented C_ namespace (GetContainerItemInfo ↔
    # C_Container.GetContainerItemInfo) was moved there: it needs calls in 2+ files to count as present
    twins = {n.split(".", 1)[1] for n in funcs if n.count(".") == 1 and n.split(".")[0] in MOVED_NS}
    called = collections.Counter({n: c for n, c in called.items() if n not in twins or c >= 2})
    commit = build = ""
    try:
        out = subprocess.run(["git", "-C", str(ui_root), "log", "-1", "--format=%H %s"], capture_output=True,
                             text=True, timeout=20).stdout.strip()
        commit, _, build = out.partition(" ")
    except (OSError, subprocess.SubprocessError):
        pass
    return {
        "source": {"repo": "Gethe/wow-ui-source", "branch": "forever", "commit": commit, "build": build,
                   "game": GAME, "family": FAMILY, "lua_files": len(lua_files), "xml_files": len(xml_files),
                   "skipped_addons": len(skipped)},
        "funcs": funcs, "methods": methods, "events": events, "tables": tables,
        "framexml": {"defined": sorted(defined), "called": sorted(called), "frames": sorted(frames),
                     "fallback": sorted(set(fallback) - set(called)),
                     "shim": sorted(shim_defined), "event_strings": sorted(ev_strings)},
    }


def save_snapshot(snap: dict):
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    raw = json.dumps(snap, sort_keys=True, separators=(",", ":")).encode("utf-8")
    with gzip.GzipFile(SNAPSHOT, "wb", mtime=0) as g:
        g.write(raw)


def load_snapshot() -> dict:
    with gzip.open(SNAPSHOT, "rb") as g:
        return json.loads(g.read().decode("utf-8"))


