LUA_GLOBALS = set("""assert collectgarbage dofile error getfenv getmetatable ipairs load loadfile loadstring module next
pairs pcall print rawequal rawget rawset require select setfenv setmetatable tonumber tostring type unpack xpcall
string table math coroutine os io debug bit _G _VERSION newproxy gcinfo""".split())
LUA_KW = set("and break do else elseif end false for function if in local nil not or repeat return then true until "
             "while self".split())
WOW_LUA_EXT = set("""strsplit strjoin strtrim strconcat strmatch strfind strsub strlen strupper strlower strrep strbyte
strchar strrev gsub format strlenutf8 tinsert tremove sort getn wipe tContains tInvert CopyTable Mixin
CreateFromMixins floor ceil abs min max sqrt mod random fastrandom Round Clamp hooksecurefunc issecurevariable
securecall geterrorhandler seterrorhandler debugstack date time""".split())


def addon_usage(addon: Path):
    uses = collections.defaultdict(list)   # api -> [file:line]
    events = collections.defaultdict(list)
    for f in sorted(addon.rglob("*.lua")):
        rel = f.relative_to(addon.parent.parent if addon.parent.name == "wow_addon" else addon).as_posix()
        src = _strip_comments(f.read_text(encoding="utf-8", errors="replace"))
        # aliases: local X = C_NS | _G.C_NS | rawget(_G, "C_NS") | g("C_NS"); also multi-assignments
        alias_at = collections.defaultdict(list)   # alias -> [(line, namespace or None)] (re-assignments end it)
        for m in re.finditer(r"(?:\blocal[ \t]+)?\b(?!local\b)([A-Za-z_][\w \t,]*?)[ \t]*=[ \t]*([^\n=][^\n]*)", src):
            names = [n.strip() for n in m.group(1).split(",")]
            vals = [v.strip() for v in re.split(r",(?![^(]*\))", m.group(2))]
            ln = src.count("\n", 0, m.start()) + 1
            for n, v in zip(names, vals):
                if not re.match(r"^[A-Za-z_]\w*$", n):
                    continue
                mm = re.match(r"^(?:_G\.|rawget\(_G,\s*\"|(?:g|G|api)\(\")?(C_[A-Za-z]+)\b(?!\s*\.)", v)
                alias_at[n].append((ln, mm.group(1) if mm else None))

        def alias_for(a, ln):
            cur = None
            for l0, ns in alias_at.get(a, ()):
                if l0 <= ln:
                    cur = ns
            return cur
        local_names = set(re.findall(r"\blocal\s+function\s+([A-Za-z_]\w*)", src))
        for m in re.finditer(r"\blocal\s+([\w\s,]+?)\s*(?:=|\n|$)", src):
            local_names.update(n.strip() for n in m.group(1).split(",") if n.strip())
        local_names.update(re.findall(r"\bfunction\s*[\w.:]*\(([^)]*)\)", src) and
                           [p.strip() for ps in re.findall(r"\bfunction\s*[\w.:]*\(([^)]*)\)", src)
                            for p in ps.split(",")] or [])
        for i, line in enumerate(src.split("\n"), 1):
            where = "%s:%d" % (rel, i)
            for m in re.finditer(r"\b(C_[A-Za-z]+)\s*(?:\.\s*([A-Za-z_]\w*)|\[\s*\"([A-Za-z_]\w*)\"\s*\])", line):
                uses[m.group(1) + "." + (m.group(2) or m.group(3))].append(where)
            for m in re.finditer(r"(?:\b(?:g|G|api)\(\"(C_[A-Za-z]+)\"\)|\(\s*(?:g|G|api)\(\"(C_[A-Za-z]+)\"\)\s*or\s*\{\}\s*\))"
                                 r"\s*\.\s*([A-Za-z_]\w*)", line):
                uses[(m.group(1) or m.group(2)) + "." + m.group(3)].append(where)
            for a in alias_at:
                if a not in line:
                    continue
                ns = alias_for(a, i)
                if not ns:
                    continue
                for m in re.finditer(r"(?<![\w.])%s\s*(?:\.\s*([A-Z]\w*)|\[\s*\"([A-Z]\w*)\"\s*\])" % re.escape(a), line):
                    uses[ns + "." + (m.group(1) or m.group(2))].append(where)
            for m in re.finditer(r"\b_G\s*\.\s*([A-Za-z_]\w*)|\b_G\s*\[\s*\"([A-Za-z_]\w*)\"\s*\]|"
                                 r"rawget\(\s*_G\s*,\s*\"([A-Za-z_]\w*)\"\s*\)|"
                                 r"(?<![\w.:])(?:g|G|api|call|gf)\(\s*\"([A-Za-z_]\w*)\"", line):
                n = m.group(1) or m.group(2) or m.group(3) or m.group(4)
                if n and not n.startswith("TreeAI") and n not in LUA_GLOBALS:
                    uses[n].append(where)
            nostr = re.sub(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'', '""', line)
            for m in re.finditer(r"(?<![\w.:])([A-Z][A-Za-z0-9_]*)\s*\(", nostr):
                n = m.group(1)
                if n in local_names or n in LUA_KW or n.startswith("TreeAI") or n in LUA_GLOBALS:
                    continue
                uses[n].append(where)
            for m in re.finditer(r"(?:RegisterEvent|RegisterUnitEvent|RegisterEvents?|Listen|On)\(\s*(?:[\w.]+\s*,\s*)?"
                                 r"\"([A-Z][A-Z0-9_]{3,})\"", line):
                events[m.group(1)].append(where)
            for m in re.finditer(r"\"([A-Z][A-Z0-9]+(?:_[A-Z0-9]+)+)\"", line):
                if m.group(1) not in events or where not in events[m.group(1)]:
                    events.setdefault(m.group(1) + "?", []).append(where)
    # "?" = an upper-case string that may be an event (only reported when it is a real event)
    return uses, events


