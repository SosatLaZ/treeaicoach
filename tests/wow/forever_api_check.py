PROBE = r"""
local here, flavor, mockfile = arg[1], arg[2], arg[3]
local M = dofile(mockfile or (here .. "/wowmock.lua"))
M.Install(flavor)
local out = {}
local function emit(s) out[#out + 1] = s end
local function shape(f, args)
  local r = { pcall(f, unpack(args)) }
  if not r[1] then return "error" end
  local n = select("#", unpack(r)) - 1
  local parts = {}
  for i = 2, n + 1 do
    local v = r[i]
    if type(v) == "table" and not rawget(v, "__kind") then
      local ks = {}
      for k in pairs(v) do if type(k) == "string" then ks[#ks + 1] = k end end
      table.sort(ks)
      parts[#parts + 1] = "{" .. table.concat(ks, ",") .. "}"
    else parts[#parts + 1] = type(v) end
  end
  return table.concat(parts, ";")
end
local SAMPLE = { unit = "player", unitToken = "player", unitGUID = "player", questID = 5101, questLogIndex = 1,
  spellID = 75, spellIdentifier = 75, itemID = 4540, bagIndex = 0, containerIndex = 0, slotIndex = 1, uiMapID = 1424 }
for k, v in pairs(_G) do
  if type(v) == "function" then emit("G\t" .. k)
  elseif type(v) == "table" and type(k) == "string" and k:match("^C_") then
    for k2, f in pairs(v) do if type(f) == "function" then emit("G\t" .. k .. "." .. k2) end end
  end
end
local probes = io.read("*a")
for line in probes:gmatch("[^\n]+") do
  local name, argnames = line:match("^(%S+)\t?(.*)$")
  local ns, fn = name:match("^(C_%w+)%.(%w+)$")
  local f = ns and rawget(_G, ns) and rawget(_G, ns)[fn] or (not ns and rawget(_G, name))
  if type(f) == "function" then
    local args = {}
    for a in argnames:gmatch("[^,]+") do args[#args + 1] = SAMPLE[a] == nil and 1 or SAMPLE[a] end
    emit("S\t" .. name .. "\t" .. shape(f, args))
  end
end
io.write(table.concat(out, "\n"), "\n")
"""


MOCK_FILE = None   # --mock FILE: probe another wowmock.lua (e.g. an older one, to count what changed)


def mock_surface(names_with_args):
    lua = shutil.which("lua5.1")
    if not lua:
        return None, {}
    probe = HERE / ".forever_probe.lua"
    probe.write_text(PROBE, encoding="utf-8")
    try:
        res = subprocess.run([lua, str(probe), str(HERE), "forever"] + ([str(MOCK_FILE)] if MOCK_FILE else []),
                             input="\n".join(names_with_args),
                             capture_output=True, text=True, timeout=120, cwd=ROOT)
    finally:
        probe.unlink(missing_ok=True)
    have, shapes = set(), {}
    for ln in res.stdout.splitlines():
        parts = ln.split("\t")
        if parts[0] == "G" and len(parts) > 1:
            have.add(parts[1])
        elif parts[0] == "S" and len(parts) > 2:
            shapes[parts[1]] = parts[2]
    if res.returncode != 0 and not have:
        print(res.stderr, file=sys.stderr)
    return have, shapes


