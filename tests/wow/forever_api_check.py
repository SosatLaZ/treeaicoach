SECRET_CODES = {  # documentation predicate -> short code the mock understands
    "SecretReturns": "R", "SecretWhenUnitIdentityRestricted": "id", "SecretWhenUnitNameIdentityRestricted": "name",
    "SecretWhenUnitHealthMaxRestricted": "hpmax", "SecretWhenUnitStatsRestricted": "stats",
    "SecretWhenUnitAuraRestricted": "aura", "SecretWhenUnitSpellCastRestricted": "cast",
    "SecretWhenUnitPowerRestricted": "power", "SecretWhenUnitPowerMaxRestricted": "powermax",
    "SecretWhenUnitThreatStateRestricted": "threat", "SecretWhenUnitThreatValuesRestricted": "threatv",
    "SecretWhenUnitComparisonRestricted": "cmp", "SecretWhenCooldownsRestricted": "cd",
    "SecretWhenInCombat": "combat", "SecretInChatMessagingLockdown": "chat", "SecretWhenUnitPossessionRestricted": "id",
    "SecretWhenLossOfControlInfoRestricted": "loc", "SecretWhenTotemSlotSecret": "combat",
    "SecretWhenEncounterEvent": "encounter", "SecretInActivePvPMatch": "pvp", "SecretWhenAurasRestricted": "aura",
    "SecretPayloads": "R",
}


def _code(f: dict) -> str:
    parts = []
    sa = f.get("SecretArguments")
    if sa in ("AllowedWhenUntainted", "NotAllowed"):
        parts.append("A")
    if f.get("IsProtectedFunction") == "true" or f.get("IsProtectedFunction") is True:
        parts.append("P")
    if f.get("HasRestrictions") in ("true", True):
        parts.append("H")
    sec = sorted({SECRET_CODES[k] for k in f if k in SECRET_CODES})
    if sec:
        parts.append("s:" + ",".join(sec))
    return " ".join(parts)


def _lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _wrap_words(words, width=118):
    lines, cur = [], ""
    for w in words:
        if len(cur) + len(w) + 1 > width:
            lines.append(cur)
            cur = ""
        cur = (cur + " " + w) if cur else w
    if cur:
        lines.append(cur)
    return lines


def ref_sets(snap: dict):
    """(api {name: code}, function-like globals, NS.member names, shim-only names, events {name: code})"""
    fx = snap["framexml"]
    called = set(fx["called"])
    defined = set(fx["defined"])
    api = {n: _code(v["f"]) for n, v in snap["funcs"].items()}
    lower = re.compile(r"[a-z]")   # ALL_CAPS constants are not pruned by the mock: not needed here (report: snapshot)
    # the mock prunes FUNCTIONS only (global ones and C_* members): frames, mixins and constants stay out of this list
    glob = sorted(set(n for n in defined | called if "." not in n and lower.search(n) and not n.endswith("Mixin"))
                  - set(api))
    mem = sorted(set(n for n in defined | called if n.startswith("C_") and n.count(".") == 1) - set(api))
    shim = sorted(set(fx["shim"]) - set(api) - set(glob) - set(mem))
    events = {e: _code(v["f"]) for e, v in snap["events"].items()}
    for e in fx["event_strings"]:
        events.setdefault(e, "")
    return api, glob, mem, shim, events


def write_lua_ref(snap: dict):
    api, glob, mem, shim, events = ref_sets(snap)
    src = snap["source"]
    out = ["-- forever_ref.lua — GENERATED by tests/wow/forever_api_check.py from %s %s « %s » (%s): do not edit."
           % (src["repo"], src["branch"], src["build"], src["commit"][:7]),
           "-- What the real WoW: Forever client (game type camelot) has, for wowmock.lua's « forever » flavour.",
           "-- api: one « Name flags » per line; flags: A = secret arguments refused from addon code, P = protected,",
           "--   H = hardware event / restricted, s:<codes> = secret returns under these restrictions (R = always).",
           "-- globals / members: undocumented functions Blizzard's camelot FrameXML defines or calls (C_* members).",
           "-- shim: only in Blizzard_Deprecated* (CVar loadDeprecationFallbacks) = treated as absent.",
           "-- events: « NAME flags » (s:<codes> = payload secret under these restrictions, H = forbidden to addons).",
           "-- enums: « Enum Key=value,Key=value » per line.",
           "return {", "build = %s," % _lua_str(src["build"]), "api = [["]
    out += ["%s %s" % (n, api[n].replace(" ", "|")) if api[n] else n for n in sorted(api)]
    out += ["]],", "globals = [["] + _wrap_words(glob) + ["]],", "members = [["] + _wrap_words(mem) + ["]],"]
    out += ["shim = [["] + _wrap_words(shim) + ["]],", "events = [["]
    out += ["%s %s" % (e, events[e].replace(" ", "|")) if events[e] else e for e in sorted(events)]
    out += ["]],", "enums = [["]
    for name in sorted(snap["tables"]):
        t = snap["tables"][name]
        if t.get("t") != "Enumeration" or not t.get("v"):
            continue
        vals = ",".join("%s=%d" % (k, v) for k, v in sorted(t["v"].items(), key=lambda kv: (kv[1], kv[0]))
                        if re.match(r"^[A-Za-z_]\w*$", k))
        out.append("%s %s" % (name, vals))
    out += ["]],", "}"]
    text = "\n".join(out) + "\n"
    if not LUA_REF.exists() or LUA_REF.read_text(encoding="utf-8") != text:
        LUA_REF.write_text(text, encoding="utf-8")


