# Respec (« réinitialiser les talents ») fees: Classic schedule 1 po, 5 po, then +5 po per reset up to 50 po;
# Forever lets the fee decay back over time (exact decay not published → estimate: −5 po per month without a
# reset). Dual spec: 50 po once at level 40.
DUAL_SPEC_COST_GOLD = 50
DUAL_SPEC_LEVEL = 40


def respec_cost_gold(resets_done: int, months_since_last: float = 0.0) -> int:
    """Estimated next respec fee in gold (Classic ladder 1, 5, 10, … 50, decaying −5 po/month)."""
    try:
        n = max(0, int(resets_done))
        ladder = 1 if n == 0 else min(50, 5 * n)
        decay = int(max(0.0, float(months_since_last))) * 5
        return max(1, ladder - decay) if n else 1
    except (TypeError, ValueError):
        return 1
