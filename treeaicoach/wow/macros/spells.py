def lookup(cls: str, key: str) -> tuple[int, str, bool] | None:
    """(spell_id, french_name, is_pet) for a template key, or None."""
    for table, pet in ((SPELLS.get(cls, {}), False), (COMMON, False), (PET.get(cls, {}), True)):
        if key in table:
            sid, name = table[key]
            return sid, name, pet
    return None
