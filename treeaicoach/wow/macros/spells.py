def lookup(cls: str, key: str) -> tuple[int, str, str] | None:
    """(id, French name, flags) of a class spell, racial or pet ability; None if unknown."""
    hit = SPELLS.get(cls, {}).get(key)
    return hit if hit is not None else COMMON.get(key)


def is_talent(cls: str, key: str) -> bool:
    return any(key in t for t in TALENTS.get(cls, {}).values())


def spec_ids(cls: str) -> tuple[str, ...]:
    return tuple(s[0] for s in SPECS.get(cls, ()))
